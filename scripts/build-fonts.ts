// Generates the label font catalog from the @fontsource packages: which file covers which
// characters, so the text engine loads a face only when a label needs it.
//   packages/core/src/text/catalog/faces.ts     Inter, Vazirmatn, Noto Sans Hebrew subsets
//   packages/core/src/text/catalog/cjk-*.ts     Noto Sans SC, JP and KR slices (loaded lazily)
// Run: node scripts/build-fonts.ts             (after changing a font package or its version)

import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(new URL('../packages/core/package.json', import.meta.url));
const OUT = new URL('../packages/core/src/text/catalog/', import.meta.url);
const WEIGHTS = [400, 500] as const;
const HEADER =
  '// Generated by scripts/build-fonts.ts from the @fontsource packages. Do not edit.\n';

interface Face {
  readonly name: string;
  readonly file: string;
  readonly ranges: string;
}

/** Reads every @font-face of one package and weight: its subset name, WOFF file and ranges. */
async function faces(pkg: string, weight: number): Promise<Face[]> {
  const dir = dirname(require.resolve(`${pkg}/package.json`));
  const css = await readFile(join(dir, `${weight}.css`), 'utf8');
  const result: Face[] = [];
  for (const block of css.split('@font-face').slice(1)) {
    const file = /url\(\.\/files\/([^)]+\.woff)\)/.exec(block)?.[1];
    const ranges = /unicode-range:\s*([^;]+);/.exec(block)?.[1];
    if (!file || !ranges) throw new Error(`${pkg} ${weight}: unexpected @font-face block.`);
    const name = /-([^-]+(?:-ext)?)-\d+-normal\.woff$/.exec(file)?.[1] ?? file;
    result.push({ name, file, ranges: ranges.replaceAll('U+', '').toLowerCase() });
  }
  return result;
}

const version = async (pkg: string) =>
  (
    JSON.parse(await readFile(require.resolve(`${pkg}/package.json`), 'utf8')) as {
      version: string;
    }
  ).version;

// Subsets per family, in fallback order within the family.
const SUBSET_FAMILIES = [
  {
    family: 'Inter',
    pkg: '@fontsource/inter',
    subsets: ['latin', 'latin-ext', 'greek', 'greek-ext', 'cyrillic', 'cyrillic-ext', 'vietnamese'],
  },
  { family: 'Vazirmatn', pkg: '@fontsource/vazirmatn', subsets: ['arabic'] },
  { family: 'Noto Sans Hebrew', pkg: '@fontsource/noto-sans-hebrew', subsets: ['hebrew'] },
] as const;

const CJK = [
  { key: 'sc', family: 'Noto Sans SC', pkg: '@fontsource/noto-sans-sc' },
  { key: 'jp', family: 'Noto Sans JP', pkg: '@fontsource/noto-sans-jp' },
  { key: 'kr', family: 'Noto Sans KR', pkg: '@fontsource/noto-sans-kr' },
] as const;

const lines: string[] = [];
for (const { family, pkg, subsets } of SUBSET_FAMILIES) {
  for (const weight of WEIGHTS) {
    const all = await faces(pkg, weight);
    for (const subset of subsets) {
      const face = all.find(
        (f) => f.file === `${pkg.split('/')[1]}-${subset}-${weight}-normal.woff`,
      );
      if (!face) throw new Error(`${pkg}: no ${subset} subset at weight ${weight}.`);
      lines.push(
        `  { family: '${family}', weight: ${weight}, package: '${pkg}', file: '${face.file}', ranges: '${face.ranges}' },`,
      );
    }
  }
}

const versions = await Promise.all(
  [...SUBSET_FAMILIES, ...CJK].map(async (f) => `//   ${f.pkg} ${await version(f.pkg)}`),
);

await writeFile(
  new URL('faces.ts', OUT),
  `${HEADER}${versions.join('\n')}\n\nimport type { CatalogFace } from './types.ts';\n\n` +
    `/** Faces with their character ranges, in fallback order. */\nexport const FACES: readonly CatalogFace[] = [\n${lines.join('\n')}\n];\n\n` +
    `/** CJK families: one numbered slice per file, so only the slices a label needs are loaded. */\n` +
    `export const CJK_FAMILIES = {\n${CJK.map((c) => `  ${c.key}: { family: '${c.family}', package: '${c.pkg}', prefix: '${c.pkg.split('/')[1]}' },`).join('\n')}\n} as const;\n`,
);

for (const { key, pkg } of CJK) {
  const [regular, medium] = await Promise.all(WEIGHTS.map((w) => faces(pkg, w)));
  // Numbered slices only; the named Latin and Cyrillic subsets are covered by Inter.
  const numbered = regular!.filter((face) => /-\d+-400-normal\.woff$/.test(face.file));
  const slices = numbered.map((face) => {
    const slice = /-(\d+)-400-normal\.woff$/.exec(face.file)![1]!;
    const twin = medium!.find((m) => m.file === face.file.replace('-400-', '-500-'));
    if (twin?.ranges !== face.ranges)
      throw new Error(`${pkg}: slice ${slice} differs between weights.`);
    return `${slice}:${face.ranges}`;
  });
  await writeFile(
    new URL(`cjk-${key}.ts`, OUT),
    `${HEADER}\n/** "slice:ranges" entries separated by ";", ranges as hex "start-end" or "code". */\nexport const SLICES =\n  '${slices.join(';')}';\n`,
  );
}

console.log(`Wrote ${lines.length} faces and ${CJK.length} CJK slice tables.`);
